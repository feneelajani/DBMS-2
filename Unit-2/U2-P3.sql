DECLARE
    CURSOR c_emp IS
        SELECT ename, deptno, sal
        FROM emp
        ORDER BY sal DESC;

    v_name   emp.ename%TYPE;
    v_dept   emp.deptno%TYPE;
    v_sal    emp.sal%TYPE;

BEGIN
    OPEN c_emp;

    LOOP
        FETCH c_emp INTO v_name, v_dept, v_sal;

        EXIT WHEN c_emp%NOTFOUND OR c_emp%ROWCOUNT > 5;

        DBMS_OUTPUT.PUT_LINE(
            'Name : ' || v_name ||
            '  Department : ' || v_dept ||
            '  Basic Salary : ' || v_sal
        );
    END LOOP;

    CLOSE c_emp;
END;
